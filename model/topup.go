// topUpQueryWindowSeconds 限制充值记录查询的时间窗口（秒）。
const topUpQueryWindowSeconds int64 = 30 * 24 * 60 * 60

// topUpQueryCutoff 返回允许查询的最早 create_time（秒级 Unix 时间戳）。
func topUpQueryCutoff() int64 {
	return common.GetTimestamp() - topUpQueryWindowSeconds
}

func GetUserTopUps(userId int, pageInfo *common.PageInfo) (topups []*TopUp, total int64, err error) {
	// Start transaction
	tx := DB.Begin()
	if tx.Error != nil {
		return nil, 0, tx.Error
	}
	defer func() {
		if r := recover(); r != nil {
			tx.Rollback()
		}
	}()

	cutoff := topUpQueryCutoff()

	// Get total count within transaction
	err = tx.Model(&TopUp{}).Where("user_id = ? AND create_time >= ?", userId, cutoff).Count(&total).Error
	if err != nil {
		tx.Rollback()
		return nil, 0, err
	}

	// Get paginated topups within same transaction
	err = tx.Where("user_id = ? AND create_time >= ?", userId, cutoff).Order("id desc").Limit(pageInfo.GetPageSize()).Offset(pageInfo.GetStartIdx()).Find(&topups).Error
	if err != nil {
		tx.Rollback()
		return nil, 0, err
	}

	// Commit transaction
	if err = tx.Commit().Error; err != nil {
		return nil, 0, err
	}

	return topups, total, nil
}

// GetUserTotalTopUpAmount returns the total quota credited by successful
// online top-up orders. Pending and failed orders are intentionally excluded.
func GetUserTotalTopUpAmount(userId int) (int64, error) {
	var total int64
	err := DB.Model(&TopUp{}).
		Where("user_id = ? AND status = ?", userId, common.TopUpStatusSuccess).
		Select("COALESCE(SUM(amount), 0)").
		Scan(&total).Error
	return total, err
}

// GetAdminUserTopUps returns a single user's complete top-up history, including
// orders outside the self-service history window. Call only from admin routes.
func GetAdminUserTopUps(userID int, keyword string, pageInfo *common.PageInfo) (topups []*TopUp, total int64, err error) {
	if userID <= 0 {
		return nil, 0, errors.New("invalid user ID")
	}
	err = DB.Transaction(func(tx *gorm.DB) error {
		query := tx.Model(&TopUp{}).Where("user_id = ?", userID)
		if keyword != "" {
			pattern, err := sanitizeLikePattern(keyword)
			if err != nil {
				return err
			}
			query = query.Where("trade_no LIKE ? ESCAPE '!'", pattern)
		}
		if err := query.Count(&total).Error; err != nil {
			return err
		}
		return query.Order("id desc").Limit(pageInfo.GetPageSize()).Offset(pageInfo.GetStartIdx()).Find(&topups).Error
	})
	return topups, total, err
}

